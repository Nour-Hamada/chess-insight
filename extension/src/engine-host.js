import { Chess } from 'chess.js';
import { parseEngineLine } from '../../src/review.js';

let worker, ready, active = null, queue = [], serial = 0;
const latest = new Map();
function waitFor(predicate, command, timeout = 45000) {
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => { cleanup(); reject(new Error('انتهت مهلة المحرك.')); }, timeout);
    const onLine = e => { for (const line of String(e.data).split(/\r?\n/)) if (predicate(line)) { cleanup(); resolve(line); break; } };
    const onError = () => { cleanup(); reject(new Error('تعذر تحميل محرك الشطرنج.')); };
    function cleanup() { clearTimeout(timer); worker?.removeEventListener('message', onLine); worker?.removeEventListener('error', onError); }
    worker.addEventListener('message', onLine); worker.addEventListener('error', onError);
    worker.postMessage(command);
  });
}
async function ensureReady() {
  if (!ready) ready = (async () => {
    const js = chrome.runtime.getURL('engine/stockfish-19-lite-single.js');
    const wasm = chrome.runtime.getURL('engine/stockfish-19-lite-single.wasm');
    worker = new Worker(js + '#' + encodeURIComponent(wasm));
    await waitFor(x => x === 'uciok', 'uci');
    worker.postMessage('setoption name Hash value 32');
    await waitFor(x => x === 'readyok', 'isready');
  })().catch(e => { worker?.terminate(); worker = null; ready = null; throw e; });
  await ready;
}
function validatedPosition(fen, position) {
  // Only accept a legal, equivalent position command generated by our tracker.
  if (typeof position !== 'string' || position.length > 20000 || /[\r\n]/.test(position)) return `position fen ${fen}`;
  const match = position.match(/^position fen (.+?)(?: moves ([a-h1-8qrbn ]+))?$/);
  if (!match) return `position fen ${fen}`;
  try {
    const board = new Chess(match[1]);
    for (const uci of (match[2] || '').split(' ').filter(Boolean)) board.move({ from: uci.slice(0, 2), to: uci.slice(2, 4), promotion: uci[4] });
    if (board.fen() === fen) return position;
  } catch {}
  return `position fen ${fen}`;
}
async function search(job) {
  const board = new Chess(job.fen);
  if (board.isGameOver()) return { cpWhite: board.isCheckmate() ? (board.turn() === 'w' ? -10000 : 10000) : 0, terminal: board.isCheckmate() ? 'mate' : 'draw', best: null, depth: 0 };
  await ensureReady();
  if (latest.get(job.clientId) !== job.serial) return { stale: true };
  let result = null;
  const onInfo = e => {
    for (const line of String(e.data).split(/\r?\n/)) {
      const info = parseEngineLine(line, job.fen);
      if (info && info.multiPv === 1 && !info.bound) result = { ...info, mate: /score mate (-?\d+)/.exec(line)?.[1] ?? null };
    }
  };
  worker.addEventListener('message', onInfo);
  const depth = Math.max(12, Math.min(20, Number(job.depth) || 14));
  worker.postMessage('setoption name MultiPV value 1');
  worker.postMessage(validatedPosition(job.fen, job.position));
  try {
    const line = await waitFor(x => x.startsWith('bestmove '), `go depth ${depth}`, 90000);
    if (latest.get(job.clientId) !== job.serial) return { stale: true };
    if (!result) throw new Error('لم يصل تقييم صالح من المحرك.');
    const best = line.split(' ')[1];
    const move = board.move({ from: best.slice(0, 2), to: best.slice(2, 4), promotion: best[4] });
    return { ...result, best, bestSan: move.san, mate: result.mate == null ? null : Number(result.mate) };
  } catch (e) {
    worker?.terminate(); worker = null; ready = null;
    throw e;
  } finally { worker?.removeEventListener('message', onInfo); }
}
async function pump() {
  if (active || !queue.length) return;
  const job = queue.shift(); active = job;
  try { job.respond(await search(job)); } catch (e) { job.respond({ error: e.message }); }
  finally { active = null; pump(); }
}
chrome.runtime.onMessage.addListener((message, sender, respond) => {
  if (message?.target !== 'engine' || sender.id !== chrome.runtime.id) return false;
  if (message.type === 'cancel') {
    latest.delete(message.clientId);
    queue = queue.filter(job => { if (job.clientId === message.clientId) { job.respond({ stale: true }); return false; } return true; });
    if (active?.clientId === message.clientId) worker?.postMessage('stop');
    return false;
  }
  if (message.type !== 'analyze') return false;
  try { new Chess(message.fen); } catch { respond({ error: 'الوضعية غير قانونية.' }); return false; }
  const job = { ...message, respond, serial: ++serial };
  latest.set(job.clientId, job.serial);
  queue = queue.filter(old => { if (old.clientId === job.clientId) { old.respond({ stale: true }); return false; } return true; });
  queue.push(job);
  if (active?.clientId === job.clientId) worker?.postMessage('stop');
  pump();
  return true;
});
